// NIST SP 800-38A Appendix F.5.1 AES-128-CTR known-answer-test.
extern crate cryptography_verus;
use cryptography_verus::algorithms::symmetric::aes128_ctr::aes128_ctr_encrypt;

fn to_hex_vec(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push_str(&format!("{:02x}", b));
    }
    s
}

fn main() {
    println!("NIST SP 800-38A F.5.1 AES-128-CTR KAT cross-check (Verus build)");

    let key: [u8; 16] = [
        0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f,
        0x3c,
    ];
    let iv: [u8; 16] = [
        0xf0, 0xf1, 0xf2, 0xf3, 0xf4, 0xf5, 0xf6, 0xf7, 0xf8, 0xf9, 0xfa, 0xfb, 0xfc, 0xfd, 0xfe,
        0xff,
    ];
    // F.5.1: 4 blocks of plaintext.
    let plaintext: Vec<u8> = vec![
        0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17,
        0x2a, 0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c, 0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf,
        0x8e, 0x51, 0x30, 0xc8, 0x1c, 0x46, 0xa3, 0x5c, 0xe4, 0x11, 0xe5, 0xfb, 0xc1, 0x19, 0x1a,
        0x0a, 0x52, 0xef, 0xf6, 0x9f, 0x24, 0x45, 0xdf, 0x4f, 0x9b, 0x17, 0xad, 0x2b, 0x41, 0x7b,
        0xe6, 0x6c, 0x37, 0x10,
    ];
    let expected = "874d6191b620e3261bef6864990db6ce9806f66b7970fdff8617187bb9fffdff5ae4df3edbd5d35e5b4f09020db03eab1e031dda2fbe03d1792170a0f3009cee";

    let ct = aes128_ctr_encrypt(&key, &iv, &plaintext);
    let got = to_hex_vec(&ct);
    if got == expected {
        println!("  PASS  F.5.1 four blocks");
        println!("KAT_RESULT: SUCCESS (1/1)");
        std::process::exit(0);
    } else {
        println!("  FAIL");
        println!("    expected {}", expected);
        println!("    got      {}", got);
        println!("KAT_RESULT: FAIL");
        std::process::exit(1);
    }
}
