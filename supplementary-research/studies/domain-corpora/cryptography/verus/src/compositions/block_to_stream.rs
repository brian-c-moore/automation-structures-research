// BlockToStreamConversion.
//
// Counter-mode keystream construction: for each
// block index i, the keystream block is E(K, counter || nonce + i),
// then ciphertext[i] = plaintext[i] XOR keystream[i]. Used in AES-CTR
// and ChaCha20 (when ChaCha20 is the block cipher, the "encrypt" is
// the ChaCha20 block function).
//
// The TLAPS proof at supplementary-research/studies/domain-corpora/cryptography/tla/compositions/
// BlockToStreamConversion_Proof.tla closes 312 obligations with the
// CountersUsedEqualsRange strengthening (counters_used =
// InitialCounter..(InitialCounter + next_block - 2)).
//
// For Verus, the keystream is generated by applying a block cipher
// (concrete: wrapping_mul + permute composition) to incrementing
// counters; the ciphertext is the XOR of plaintext and keystream.
//
// Verification boundary: written contracts plus named external-body assumptions.

use vstd::prelude::*;

verus! {

/// Concrete toy block function for the structural stream-conversion
/// relation. It does not establish AES or ChaCha20 conformance.
pub open spec fn block_cipher_spec(key: u64, counter: u64) -> u64 {
    key.wrapping_add(counter.wrapping_mul(0x9E3779B97F4A7C15u64))
}

pub fn block_cipher(key: u64, counter: u64) -> (r: u64)
    ensures r == block_cipher_spec(key, counter),
{
    key.wrapping_add(counter.wrapping_mul(0x9E3779B97F4A7C15u64))
}

/// Keystream block at counter `i` starting from `initial_counter`.
pub open spec fn keystream_at_spec(key: u64, initial_counter: u64, i: int) -> u64 {
    block_cipher_spec(key, initial_counter.wrapping_add(i as u64))
}

/// Encrypt: ciphertext = plaintext XOR keystream. For each plaintext
/// block, generate the corresponding keystream block via the counter
/// and XOR. The TLAPS CiphertextEntryCorrect invariant (each
/// ciphertext[i] = XOR of plaintext[i] and keystream[i]) is captured
/// by the loop's ensures clause.
pub fn encrypt_ctr(key: u64, initial_counter: u64, plaintext: &[u64]) -> (ct: Vec<u64>)
    requires plaintext@.len() as int <= 1_000_000_000,
    ensures
        ct@.len() == plaintext@.len() as int,
        forall|i: int| 0 <= i < ct@.len()
            ==> ct@[i] == plaintext@[i] ^ keystream_at_spec(key, initial_counter, i),
{
    let n: usize = plaintext.len();
    let mut ct: Vec<u64> = Vec::new();
    let mut i: usize = 0;
    while i < n
        invariant
            i <= n,
            n == plaintext@.len(),
            ct@.len() == i as int,
            forall|j: int| 0 <= j < i as int
                ==> ct@[j] == plaintext@[j] ^ keystream_at_spec(key, initial_counter, j),
        decreases n - i,
    {
        let ks = block_cipher(key, initial_counter.wrapping_add(i as u64));
        ct.push(plaintext[i] ^ ks);
        i = i + 1;
    }
    ct
}

}
