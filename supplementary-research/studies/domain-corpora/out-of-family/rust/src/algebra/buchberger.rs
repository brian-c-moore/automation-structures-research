/// Buchberger's criterion: every S-polynomial of the basis reduces to
/// zero modulo the basis. This *is* the definition of a Groebner basis
/// made checkable, and it is re-derived here from the output alone.
pub fn satisfies_buchberger_criterion(g: &[Poly]) -> bool {
    for j in 0..g.len() {
        for i in 0..j {
            let s = s_polynomial(&g[i], &g[j]);
            if !normal_form(&s, g).is_zero() {
                return false;
            }
        }
    }
    true
}

/// `f` lies in the ideal generated by the Groebner basis `g`.
pub fn in_ideal(g: &[Poly], f: &Poly) -> bool {
    normal_form(f, g).is_zero()
}

/// Minimal (no leading monomial divides another's), interreduced (no
/// term of any element is divisible by another's leading monomial), and
/// monic.
pub fn is_reduced_basis(g: &[Poly]) -> bool {
    for (i, a) in g.iter().enumerate() {
        if a.is_zero() || a.lc() != Some(Rat::ONE) {
            return false;
        }
        for (j, b) in g.iter().enumerate() {
            if i == j {
                continue;
            }
            let bm = b.lm().expect("non-zero");
            for (m, _) in &a.terms {
                if bm.divides(m) {
                    return false;
                }
            }
        }
    }
    true
}
