//! **Buchberger's algorithm** (Buchberger 1965; the textbook
//! formulation of Cox, Little & O'Shea).
//!
//! Input: generators of an ideal and a monomial order. Output: a
//! Groebner basis of the ideal — a generating set whose leading
//! monomials generate the ideal's leading-term ideal, so multivariate
//! division by it has a unique remainder and ideal membership becomes a
//! normal-form test.
//!
//! The loop is the same shape as completion's: hold a pool of pending
//! pairs; take one; form its S-polynomial; reduce it modulo the basis so
//! far; a non-zero remainder joins the basis and generates fresh pairs.
//! The pool draining is Buchberger's criterion holding, which is
//! confluence of the division algorithm.
//!
//! Minimalizing and interreducing the result gives the **reduced**
//! Groebner basis, which for a fixed monomial order is unique — the
//! property that lets a published basis serve as a reference output.

use super::monomial::Monomial;
use super::poly::Poly;
use super::rational::Rat;

/// Multivariate division: the remainder of `f` on division by `g`.
pub fn normal_form(f: &Poly, g: &[Poly]) -> Poly {
    let mut remainder = Poly::zero(f.nvars, f.order);
    let mut p = f.clone();
    while !p.is_zero() {
        let (pm, pc) = p.leading().expect("non-zero").clone();
        let mut divided = false;
        for gi in g {
            if gi.is_zero() {
                continue;
            }
            let (gm, gc) = gi.leading().expect("non-zero");
            if let Some(q) = pm.div(gm) {
                p = p.sub(&gi.mul_term(&q, pc / *gc));
                divided = true;
                break;
            }
        }
        if !divided {
            // The leading term is irreducible: move it to the remainder.
            let lt = Poly::term(f.nvars, f.order, pm.clone(), pc);
            remainder = remainder.add(&lt);
            p = p.sub(&lt);
        }
    }
    remainder
}

/// The S-polynomial of `f` and `g`: the combination that cancels their
/// leading terms.
pub fn s_polynomial(f: &Poly, g: &Poly) -> Poly {
    let (fm, fc) = f.leading().expect("non-zero");
    let (gm, gc) = g.leading().expect("non-zero");
    let l = fm.lcm(gm);
    let a = f.mul_term(&l.div(fm).expect("lcm divisible"), fc.inv());
    let b = g.mul_term(&l.div(gm).expect("lcm divisible"), gc.inv());
    a.sub(&b)
}

/// A Groebner basis of the ideal generated by `input`, or `None` if the
/// round limit was reached with pairs still pending.
pub fn groebner_basis(input: &[Poly], max_rounds: usize) -> Option<Vec<Poly>> {
    let mut basis: Vec<Poly> = input.iter().filter(|p| !p.is_zero()).cloned().collect();
    if basis.is_empty() {
        return Some(basis);
    }
    let mut pairs: Vec<(usize, usize)> = Vec::new();
    for j in 0..basis.len() {
        for i in 0..j {
            pairs.push((i, j));
        }
    }

    for _ in 0..max_rounds {
        if pairs.is_empty() {
            return Some(basis);
        }
        let (i, j) = pairs.remove(select_pair(&pairs, &basis));
        let s = s_polynomial(&basis[i], &basis[j]);
        let r = normal_form(&s, &basis);
        if !r.is_zero() {
            let fresh = basis.len();
            for k in 0..fresh {
                pairs.push((k, fresh));
            }
            basis.push(r.monic());
        }
    }
    None
}

/// The reduced Groebner basis: minimal, interreduced, monic, and
/// presented in descending leading-monomial order.
pub fn reduced_groebner_basis(input: &[Poly], max_rounds: usize) -> Option<Vec<Poly>> {
    let basis = groebner_basis(input, max_rounds)?;
    if basis.is_empty() {
        return Some(basis);
    }

    // Minimalize: drop any element whose leading monomial another
    // element's leading monomial divides (keeping the earlier of a tie).
    let mut minimal: Vec<Poly> = Vec::new();
    for (i, g) in basis.iter().enumerate() {
        let gm = g.lm().expect("non-zero");
        let redundant = basis.iter().enumerate().any(|(j, h)| {
            if i == j || h.is_zero() {
                return false;
            }
            let hm = h.lm().expect("non-zero");
            hm.divides(gm) && (hm != gm || j < i)
        });
        if !redundant {
            minimal.push(g.monic());
        }
    }

    // Interreduce: replace each element by its normal form modulo the
    // others. Its leading term survives, since no other leading monomial
    // divides it.
    let mut reduced = minimal.clone();
    for i in 0..reduced.len() {
        let others: Vec<Poly> = reduced
            .iter()
            .enumerate()
            .filter(|(j, _)| *j != i)
            .map(|(_, p)| p.clone())
            .collect();
        reduced[i] = normal_form(&reduced[i], &others).monic();
    }

    let order = reduced[0].order;
    reduced.sort_by(|a, b| {
        order.cmp(
            b.lm().unwrap_or(&Monomial::one(b.nvars)),
            a.lm().unwrap_or(&Monomial::one(a.nvars)),
        )
    });
    Some(reduced)
}

/// The pending pair whose lcm has the lowest total degree — the
/// "normal" selection strategy. Correctness does not depend on it: any
/// strategy that eventually takes every pair computes a Groebner basis.
fn select_pair(pairs: &[(usize, usize)], basis: &[Poly]) -> usize {
    let mut best = 0;
    let mut best_degree = u32::MAX;
    for (k, (i, j)) in pairs.iter().enumerate() {
        let l = basis[*i]
            .lm()
            .expect("non-zero")
            .lcm(basis[*j].lm().expect("non-zero"));
        let d = l.total_degree();
        if d < best_degree {
            best_degree = d;
            best = k;
        }
    }
    best
}

